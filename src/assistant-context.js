import { fileStem } from './workspace-utils.js';

const MAX_CONTEXT_RESIDUES = 600;

export function residueTargetId(residue) {
  const chain = String(residue?.chain || '_').trim() || '_';
  const number = `${residue?.resi ?? ''}${residue?.icode || ''}`.trim();
  return `${chain}:${number}:${String(residue?.resn || 'UNK').trim()}`;
}

function residueTarget(residue) {
  return {
    id: residueTargetId(residue),
    label: `${residue.resn} ${residue.resi}${residue.icode || ''} · chain ${residue.chain || 'unassigned'}`,
  };
}

function boundedResidues(residues, selectedKeys, question) {
  const numbers = new Set((question.match(/(?<![A-Za-z])-?\d+[A-Za-z]?(?![A-Za-z])/g) || []).map(value => value.toLowerCase()));
  const priority = residues.filter(residue => selectedKeys.has(residue.key) || numbers.has(`${residue.resi}${residue.icode || ''}`.toLowerCase()));
  const chosen = new Map(priority.map(residue => [residue.key, residue]));
  if (chosen.size < MAX_CONTEXT_RESIDUES) {
    const remaining = MAX_CONTEXT_RESIDUES - chosen.size;
    const stride = Math.max(1, residues.length / remaining);
    for (let index = 0; index < residues.length && chosen.size < MAX_CONTEXT_RESIDUES; index += stride) {
      const residue = residues[Math.floor(index)];
      chosen.set(residue.key, residue);
    }
  }
  return [...chosen.values()].slice(0, MAX_CONTEXT_RESIDUES).map(residueTarget);
}

export function buildStructureContext(object, selection, question = '') {
  if (!object?.summary) return null;
  const selected = selection?.objectId === object.id ? selection : null;
  const selectedKeys = new Set(selected?.primaryKeys || []);
  const residueIds = object.summary.residues
    .filter(residue => selectedKeys.has(residue.key))
    .map(residueTargetId);
  return {
    object_id: object.id,
    title: String(object.title || object.name || 'Untitled structure').slice(0, 260),
    description: String(object.description || '').replace(/\s+/g, ' ').trim().slice(0, 500),
    format: object.format,
    atom_count: object.summary.atomCount,
    residue_count: object.summary.residueCount,
    frame: (object.currentFrame || 0) + 1,
    frame_count: object.frameCount || 1,
    chains: object.summary.chains.map(chain => chain.id).slice(0, 100),
    ligands: object.summary.ligands.slice(0, 100).map(residueTarget),
    residues: boundedResidues(object.summary.residues, selectedKeys, question),
    selection: selected ? {
      kind: String(selected.kind || 'selection').slice(0, 80),
      label: String(selected.label || 'Current selection').slice(0, 300),
      residue_ids: residueIds.slice(0, 50),
      chain: selected.chain == null ? null : String(selected.chain).slice(0, 20),
    } : null,
  };
}

function cleanLine(value) {
  return String(value ?? '').replace(/[\r\n]+/g, ' ').trim();
}

export function createCitedReport({ question, answer, sources = [], context = null, generatedAt = new Date() }) {
  const lines = [
    '# Molecule3D literature report',
    '',
    `Generated: ${generatedAt.toISOString()}`,
    '',
    '## Question',
    '',
    cleanLine(question),
  ];
  if (context) {
    lines.push('', '## Attached structure', '', `- Object: ${cleanLine(context.title)}`, `- Format: ${cleanLine(context.format).toUpperCase()}`, `- Atoms: ${context.atom_count}`, `- Residues: ${context.residue_count}`, `- Frame: ${context.frame} of ${context.frame_count}`);
    if (context.selection?.label) lines.push(`- Selection: ${cleanLine(context.selection.label)}`);
  }
  lines.push('', '## Answer', '', String(answer || '').trim(), '', '## Sources', '');
  if (!sources.length) lines.push('No sources were returned.');
  for (const source of sources) {
    lines.push(`- ${cleanLine(source.label)} — [${cleanLine(source.title)}](${source.url})${source.publication ? ` · ${cleanLine(source.publication)}` : ''}${source.year ? ` (${cleanLine(source.year)})` : ''}`);
  }
  lines.push('', '_Generated by Molecule3D. Verify important claims against the cited publications._', '');
  return lines.join('\n');
}

export function reportFilename(context) {
  return `${fileStem(context?.title, 'molecule3d-report')}-literature-report.md`;
}
